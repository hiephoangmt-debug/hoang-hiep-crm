/** Danh sách căn rút gọn cho trang web: [tầng-id, khối, số, loại, m², m² tầng 20 (duplex)] */
export function unitIndex() {
  const out = [];
  for (const f of floors) {
    for (const b of ["N", "S"]) {
      for (const [no, [type, area]] of Object.entries(f[b])) out.push([f.id, b, no, type, area]);
    }
  }
  return out;
}

/** Khoảng diện tích theo loại căn (duplex: cộng tầng 19 + 20). */
export function typeRanges() {
  const r = {};
  const f19 = floors.find((f) => f.id === "19"), f20 = floors.find((f) => f.id === "20");
  for (const f of floors) {
    for (const b of ["N", "S"]) {
      for (const [no, [type, area]] of Object.entries(f[b])) {
        let a = area;
        if (type.startsWith("DUP")) { if (f.id !== "19") continue; a = +(area + f20[b][no][1]).toFixed(2); }
        r[type] = r[type] || [Infinity, 0, 0];
        r[type][0] = Math.min(r[type][0], a); r[type][1] = Math.max(r[type][1], a); r[type][2] += f.to - f.from + 1;
      }
    }
  }
  void f19;
  return r;
}

export const totalUnits = () => {
  // căn duplex chiếm 2 tầng (19–20) chỉ tính 1 lần
  let n = 0;
  for (const f of floors) for (const b of ["N", "S"]) for (const [, [type]] of Object.entries(f[b])) {
    if (type.startsWith("DUP") && f.id === "20") continue;
    n += f.to - f.from + 1;
  }
  return n;
};
